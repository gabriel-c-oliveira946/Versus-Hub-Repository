-- 7. VIEWS E FUNÇÕES RPC PARA CÁLCULO OFICIAL DO RANKING NO SUPABASE
-- Permite consultar ranking ordenado pelas inscrições aceitas e vitórias reais
-- ==============================================================================

-- VIEW 1: Ranking de Jogadores (Agregação por inscrições aceitas)
CREATE OR REPLACE VIEW public.vw_ranking_jogadores AS
SELECT 
    u.id,
    u.nome,
    u.email,
    u.avatar,
    u.regiao,
    COUNT(DISTINCT i.torneio_id) AS torneios_disputados,
    -- Vitórias estimadas por títulos de equipes que lidera
    COALESCE((
        SELECT COALESCE(SUM(jsonb_array_length(COALESCE(eq."torneiosGanhos", '[]'::jsonb))), 0)
        FROM public.equipes eq
        WHERE lower(trim(eq."leaderEmail")) = lower(trim(u.email)) 
           OR lower(trim(eq."leaderName")) = lower(trim(u.nome))
    ), 0) AS torneios_vencidos,
    -- Pontos computados: 300 pts por torneio ganho + 25 pts por participação confirmada
    (
        COUNT(DISTINCT i.torneio_id) * 25 + 
        COALESCE((
            SELECT COALESCE(SUM(jsonb_array_length(COALESCE(eq."torneiosGanhos", '[]'::jsonb))), 0)
            FROM public.equipes eq
            WHERE lower(trim(eq."leaderEmail")) = lower(trim(u.email)) 
               OR lower(trim(eq."leaderName")) = lower(trim(u.nome))
        ), 0) * 300
    ) AS pontos
FROM public.usuarios u
LEFT JOIN public.inscricoes i 
    ON (lower(trim(i.user_email)) = lower(trim(u.email)) 
        OR lower(trim(i.id_participante)) = lower(trim(u.email)) 
        OR i.id_participante = u.id::text) 
    AND i.status = 'Aceito'
GROUP BY u.id, u.nome, u.email, u.avatar, u.regiao
ORDER BY pontos DESC, torneios_disputados DESC, u.nome ASC;

-- VIEW 2: Ranking de Equipes (Agregação por inscrições aceitas da equipe)
CREATE OR REPLACE VIEW public.vw_ranking_equipes AS
SELECT 
    e.id,
    e.nome,
    e.tag,
    e.logo,
    e.jogos,
    e."leaderName",
    e."leaderEmail",
    COUNT(DISTINCT i.torneio_id) AS torneios_disputados,
    jsonb_array_length(COALESCE(e."torneiosGanhos", '[]'::jsonb)) AS torneios_vencidos,
    -- Pontos computados: 300 pts por torneio ganho + 25 pts por participação confirmada
    (
        COUNT(DISTINCT i.torneio_id) * 25 + 
        jsonb_array_length(COALESCE(e."torneiosGanhos", '[]'::jsonb)) * 300
    ) AS pontos
FROM public.equipes e
LEFT JOIN public.inscricoes i 
    ON (i.id_participante = e.id OR (lower(trim(i.tipo)) = 'equipe' AND i.id_participante = e.id)) 
    AND i.status = 'Aceito'
GROUP BY e.id, e.nome, e.tag, e.logo, e.jogos, e."leaderName", e."leaderEmail", e."torneiosGanhos"
ORDER BY pontos DESC, torneios_disputados DESC, e.nome ASC;

