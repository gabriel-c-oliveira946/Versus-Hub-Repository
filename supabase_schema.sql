-- 1. TABELA DE USUÁRIOS
CREATE TABLE IF NOT EXISTS public.usuarios (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nome TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    senha TEXT NOT NULL,
    "dataNasc" TEXT,
    bio TEXT DEFAULT '',
    avatar TEXT DEFAULT '/image/boneco_logo_ofc.png',
    regiao TEXT DEFAULT 'Brasil',
    "jogosFavoritos" JSONB DEFAULT '[]'::jsonb,
    plataformas JSONB DEFAULT '[]'::jsonb,
    banner TEXT DEFAULT '',
    stats JSONB DEFAULT '{"disputed": 0, "won": 0, "wins": 0, "losses": 0}'::jsonb,
    conquistas JSONB DEFAULT '[{"titulo": "Perfil Ativado", "desc": "Configure e atualize suas conquistas para o ranking no painel de perfil.", "data": "Desbloqueado"}]'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. TABELA DE TORNEIOS
CREATE TABLE IF NOT EXISTS public.torneios (
    id TEXT PRIMARY KEY,
    nome TEXT NOT NULL,
    jogo TEXT,
    data TEXT,
    status TEXT DEFAULT 'Inscrições abertas',
    "statusClass" TEXT DEFAULT 'status-aberto',
    banner TEXT,
    "criadorEmail" TEXT,
    descricao TEXT,
    categoria TEXT,
    plataforma TEXT,
    "inicioIso" TEXT,
    localizacao TEXT,
    modalidade TEXT DEFAULT 'online',
    regras TEXT,
    "taxaTipo" TEXT DEFAULT 'gratis',
    "taxaValor" TEXT DEFAULT '',
    "tipoPremio" TEXT DEFAULT 'nenhuma',
    premio1 TEXT DEFAULT '',
    premio2 TEXT DEFAULT '',
    premio3 TEXT DEFAULT '',
    "premiacaoExtra" TEXT DEFAULT '',
    requisitos TEXT DEFAULT '',
    link TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. TABELA DE EQUIPES
CREATE TABLE IF NOT EXISTS public.equipes (
    id TEXT PRIMARY KEY,
    nome TEXT NOT NULL,
    tag TEXT,
    jogos TEXT,
    plataforma TEXT,
    regiao TEXT,
    limite TEXT,
    sobre TEXT DEFAULT 'Nenhuma descrição informada.',
    logo TEXT DEFAULT '/image/logo.png',
    "leaderName" TEXT,
    "leaderAvatar" TEXT,
    "leaderEmail" TEXT,
    "torneiosGanhos" JSONB DEFAULT '[]'::jsonb,
    "torneiosAtuais" JSONB DEFAULT '[]'::jsonb,
    link TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. TABELA DE CURTIDAS (LIKES)
CREATE TABLE IF NOT EXISTS public.curtidas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    torneio_id TEXT NOT NULL,
    user_email TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT curtidas_torneio_user_unique UNIQUE (torneio_id, user_email)
);

-- 5. TABELA DE INSCRIÇÕES
CREATE TABLE IF NOT EXISTS public.inscricoes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    torneio_id TEXT NOT NULL,
    user_email TEXT NOT NULL,
    tipo TEXT DEFAULT 'individual',
    id_participante TEXT,
    status TEXT DEFAULT 'Pendente',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT inscricoes_torneio_user_unique UNIQUE (torneio_id, user_email)
);

-- 6. TABELA DE MEMBROS DE EQUIPE
CREATE TABLE IF NOT EXISTS public.membros_equipe (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    equipe_id TEXT NOT NULL,
    user_email TEXT NOT NULL,
    status TEXT DEFAULT 'Pendente',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT membros_equipe_user_unique UNIQUE (equipe_id, user_email)
);

-- Índices para otimização de consultas frequentes
CREATE INDEX IF NOT EXISTS idx_usuarios_email ON public.usuarios(email);
CREATE INDEX IF NOT EXISTS idx_curtidas_torneio ON public.curtidas(torneio_id);
CREATE INDEX IF NOT EXISTS idx_curtidas_user ON public.curtidas(user_email);
CREATE INDEX IF NOT EXISTS idx_inscricoes_torneio ON public.inscricoes(torneio_id);
CREATE INDEX IF NOT EXISTS idx_inscricoes_user ON public.inscricoes(user_email);
CREATE INDEX IF NOT EXISTS idx_membros_equipe_id ON public.membros_equipe(equipe_id);
CREATE INDEX IF NOT EXISTS idx_membros_equipe_user ON public.membros_equipe(user_email);
CREATE INDEX IF NOT EXISTS idx_equipes_leader ON public.equipes("leaderEmail");
CREATE INDEX IF NOT EXISTS idx_torneios_criador ON public.torneios("criadorEmail");

